#!/system/bin/sh
# Infinix FastCharge Fix - Service Script
# Использует ОФИЦИАЛЬНЫЙ интерфейс ядра: chgspeed_ctl + persist.sys.mutilelvel.charge
# НЕ трогает thermal, НЕ трогает chg_speed напрямую, НЕ трогает cooling devices

MODDIR=${0%/*}
CHG_CTL=/sys/devices/platform/charger/chgspeed_ctl

# -----------------------------------------------------------------------
# Ждём полной загрузки системы
# -----------------------------------------------------------------------
until [ "$(getprop sys.boot_completed)" = "1" ]; do
    sleep 2
done

# Ещё небольшая пауза чтобы chg_sence успел стартовать через init
sleep 5

# -----------------------------------------------------------------------
# ШАГ 1: Устанавливаем уровень скорости на максимум (6 = 45W).
# Init rc уже сделает это через property trigger, но на GSI init
# иногда не подхватывает persist.* при первом старте — дублируем.
# -----------------------------------------------------------------------
setprop persist.sys.mutilelvel.charge 6
sleep 1
# На всякий случай пишем и напрямую (формат "1:N" = enable:level)
echo "1:6" > "$CHG_CTL" 2>/dev/null

# -----------------------------------------------------------------------
# ШАГ 2: Цикл мониторинга — только безопасные операции
# При подключении зарядника kernel сам установит rfc_cap/pps_cap
# через PE5.0 negotiation. Наша задача — убедиться что chgspeed_ctl
# всегда указывает на уровень 6, пока заряжаемся.
# -----------------------------------------------------------------------
while true; do
    # Читаем состояние: формат "is_fast:speed"
    STATE=$(cat "$CHG_CTL" 2>/dev/null)
    IS_FAST=${STATE%%:*}
    SPEED=${STATE##*:}

    if [ "$IS_FAST" = "1" ]; then
        # Активная быстрая зарядка — если уровень упал, восстанавливаем
        if [ "$SPEED" != "6" ]; then
            echo "1:6" > "$CHG_CTL" 2>/dev/null
        fi
    else
        # Зарядник не активен или SDP/SCP не подтверждён — выставляем desired=6
        # чтобы при подключении PE5.0 адаптера немедленно выдало 45W
        echo "1:6" > "$CHG_CTL" 2>/dev/null
    fi

    sleep 3
done
